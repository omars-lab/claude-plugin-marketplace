#!/usr/bin/env python3
"""import_saved.py — read Instagram's "Download your information" export and write every saved
post, with its caption, creator, hashtags, save time and collections, to one file.

    import_saved.py --from-zip <export.zip> [--out PATH] [--never-public PATH]
    import_saved.py <export.zip or unzipped folder>          (same thing)
    import_saved.py --list [--saved PATH]                    each collection and its post count
    import_saved.py --collection NAME [--saved PATH]         that collection's post links

Defaults: --out and --saved are $INSTAGRAM_HOME/.cache/saves.json, --never-public is
$INSTAGRAM_HOME/.cache/never-public.txt (see shared/scripts/home.py).

What it reads, and what it never reads
  An export holds the whole account: messages, voice notes, logins, payment details. This script
  opens ONLY the files under a `saved/` folder whose name starts with `saved_posts` or
  `saved_collections` (.html or .json), straight from the zip, in memory. Nothing is unpacked,
  and every other file in the zip is never opened. `saved_music` is skipped on purpose.

The two export formats
  HTML (2025 on): each save is a table. A `URL` cell holds the post link, a `Caption` row holds
  the caption verbatim, an `Owner` section holds URL / Name / Username, a `Hashtags` section
  lists tags, and in saved_posts a date div after the table holds the save time
  ("Oct 12, 2026 5:53 am", local time with no zone; kept as written plus a naive ISO form).
  saved_collections: each collection is a table with Name / Type / Privacy / Update time rows
  and a `Media` section holding its posts in the same shape. Collection names can repeat, so
  collections are a list, never keyed by name.
  JSON (older exports): string_map_data or label_values records; links, authors and save
  times only, no captions.

Output ($INSTAGRAM_HOME/.cache/saves.json, gitignored there):
  {"exported": <zip name>, "account": ..., "format": "html"|"json",
   "saves": [{code, url, kind, caption, hashtags[], owner{username,name,url}, saved_at,
              saved_at_text, collections[], only_in_collection?}],
  A post can sit in a collection without being in saved_posts (seen a handful of times). It is
  kept, flagged only_in_collection, and left out of the `saves=` count in the log.
   "collections": [{name, type, privacy, updated, codes[]}]}

It also writes never-public.txt: the account name, collection names, creators' handles and
post codes, one per line. The marketplace pre-commit hook and the data repo's
`make check-public` use it to block any of them from reaching the public plugin.

If a new export reads as zero saves, add a trimmed, invented copy of its shape to
fixtures/ and test_import_saved.py, and fix the reader.

Logs: `ev=` lines on stderr (shared/scripts/log.py).
"""

import argparse
import datetime as dt
import io
import json
import os
import re
import sys
import zipfile
from html.parser import HTMLParser

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, os.pardir, os.pardir, os.pardir, "shared", "scripts"))
from home import cache  # noqa: E402
from log import log  # noqa: E402

POST = re.compile(r"https?://(?:www\.)?instagram\.com/(?:[^/?#]+/)?(p|reel|tv)/([A-Za-z0-9_-]+)")
KIND = {"p": "post", "reel": "reel", "tv": "tv"}
SAVED_FILE = re.compile(r"(^|/)saved/(saved_posts|saved_collections)[^/]*\.(html|json)$")
DATE = re.compile(r"^[A-Z][a-z]{2} \d{1,2}, \d{4} \d{1,2}:\d{2} [ap]m$")
GENERATED = re.compile(r"Generated by (\S+) on")
VOID = {"br", "img", "meta", "hr", "input", "link", "base", "col", "wbr", "source"}


# ---------------------------------------------------------------------------- reading the zip

def saved_files(path):
    """[(name, text)] for the Saved files only. Other files in the export are never opened."""
    found = []
    if zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as z:
            for name in z.namelist():
                if SAVED_FILE.search(name):
                    found.append((name, z.read(name).decode("utf-8")))
    else:
        for root, _, files in os.walk(path):
            for f in files:
                rel = os.path.relpath(os.path.join(root, f), path).replace(os.sep, "/")
                if SAVED_FILE.search("/" + rel):
                    with open(os.path.join(root, f), encoding="utf-8") as fh:
                        found.append((rel, fh.read()))
    return sorted(found)


# ---------------------------------------------------------------------------- HTML: a tiny tree

class Node:
    __slots__ = ("tag", "attrs", "kids", "parent")

    def __init__(self, tag, attrs, parent):
        self.tag, self.attrs, self.kids, self.parent = tag, attrs, [], parent

    def text(self):
        out = []
        stack = [self]
        while stack:
            n = stack.pop()
            if isinstance(n, str):
                out.append(n)
            elif n.tag == "br":
                out.append("\n")
            else:
                stack.extend(reversed(n.kids))
        return "".join(out)

    def own_text(self):
        return "".join(k for k in self.kids if isinstance(k, str))

    def elements(self, tag=None):
        """Every element below this one, in document order."""
        stack = [k for k in reversed(self.kids) if not isinstance(k, str)]
        while stack:
            n = stack.pop()
            if tag is None or n.tag == tag:
                yield n
            stack.extend(k for k in reversed(n.kids) if not isinstance(k, str))

    def up(self, tag):
        n = self.parent
        while n is not None and n.tag != tag:
            n = n.parent
        return n

    def rows(self):
        """This table's own rows (not rows of tables nested inside it)."""
        return [tr for tr in self.elements("tr") if tr.up("table") is self]


class TreeBuilder(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node("#root", {}, None)
        self.cur = self.root

    def handle_starttag(self, tag, attrs):
        node = Node(tag, dict(attrs), self.cur)
        self.cur.kids.append(node)
        if tag not in VOID:
            self.cur = node

    def handle_startendtag(self, tag, attrs):
        self.cur.kids.append(Node(tag, dict(attrs), self.cur))

    def handle_endtag(self, tag):
        n = self.cur
        while n is not None and n.tag != tag:
            n = n.parent
        if n is not None and n.parent is not None:
            self.cur = n.parent

    def handle_data(self, data):
        self.cur.kids.append(data)


def parse_html(text):
    b = TreeBuilder()
    b.feed(text)
    b.close()
    return b.root


def cells(tr):
    return [td for td in tr.elements("td") if td.up("tr") is tr]


def label_rows(table):
    """{label: value text} for a table's own two-cell rows."""
    out = {}
    for tr in table.rows():
        tds = cells(tr)
        if len(tds) == 2:
            out.setdefault(tds[0].text().strip(), tds[1].text())
    return out


def section(table, heading):
    """The element right after an <h2>heading</h2> inside this save's table, else None."""
    for h2 in table.elements("h2"):
        if h2.text().strip() == heading and h2.up("table") is table:
            sibs = [k for k in h2.parent.kids if not isinstance(k, str)]
            i = sibs.index(h2)
            return sibs[i + 1] if i + 1 < len(sibs) else None
    return None


def iso(text):
    try:
        return dt.datetime.strptime(text, "%b %d, %Y %I:%M %p").strftime("%Y-%m-%dT%H:%M")
    except (TypeError, ValueError):
        return None


def is_leaf(n):
    return not any(not isinstance(k, str) for k in n.kids)


def save_time(table):
    """saved_posts puts the save time in a leaf div that is a sibling of the box holding the
    save's table. Walk up until a level has it; stop at a level holding other saves' boxes."""
    path, n = table, table.parent
    while n is not None and n.tag != "main":
        others = [k for k in n.kids if not isinstance(k, str) and k is not path]
        for k in others:
            if k.tag == "div" and is_leaf(k) and DATE.match(k.text().strip()):
                return k.text().strip()
        if any(not is_leaf(k) for k in others):
            return None  # this level holds other saves: walked past this save's box
        path, n = n, n.parent
    return None


def read_save(a):
    """One save from its post-link anchor."""
    m = POST.search(a.attrs["href"])
    table = a.up("table")
    rows = label_rows(table)
    owner = {}
    box = section(table, "Owner")
    if box is not None:
        for t in box.elements("table"):
            got = label_rows(t)
            if "Username" in got or "Name" in got:
                owner = {"username": (got.get("Username") or "").strip() or None,
                         "name": (got.get("Name") or "").strip() or None,
                         "url": (got.get("URL") or "").strip() or None}
                break
    tags = []
    box = section(table, "Hashtags")
    if box is not None:
        for d in box.elements("div"):
            leaf = not any(not isinstance(k, str) for k in d.kids)
            t = d.text().strip()
            if leaf and t and t != "Name":
                tags.append(t)
    when = save_time(table)
    return {"code": m.group(2), "url": "https://www.instagram.com/%s/%s/" % (m.group(1), m.group(2)),
            "kind": KIND[m.group(1)], "caption": rows.get("Caption"), "hashtags": tags,
            "owner": owner or None, "saved_at": iso(when), "saved_at_text": when, "collections": []}


def post_anchors(root):
    """Anchors that are a save's own link: inside a cell whose own text is "URL"."""
    for a in root.elements("a"):
        if POST.search(a.attrs.get("href") or ""):
            td = a.up("td")
            if td is not None and td.own_text().strip() == "URL":
                yield a


def account(root):
    for n in root.elements("aside"):
        m = GENERATED.search(n.text())
        if m:
            return m.group(1)
    return None


def is_header(rows):
    return "Type" in rows and "Name" in rows


def collection_of(table, memo):
    """The collection header table around a post: the nearest table with Name and Type rows.
    memo caches label_rows per table, since a header table's subtree is its whole collection."""
    t = table.up("table")
    while t is not None:
        if id(t) not in memo:
            memo[id(t)] = label_rows(t)
        if is_header(memo[id(t)]):
            return t, memo[id(t)]
        t = t.up("table")
    return None, None


def header(rows):
    return {"name": rows["Name"].strip(), "type": rows.get("Type", "").strip() or None,
            "privacy": rows.get("Privacy", "").strip() or None,
            "updated": iso((rows.get("Update time") or "").strip()), "codes": []}


def read_html(files):
    saves, order, collections, acct = {}, [], [], None
    # saved_posts first: its copy of a save has the save time, the collections copy does not.
    for name, text in sorted(files, key=lambda f: "saved_collections" in f[0]):
        root = parse_html(text)
        acct = acct or account(root)
        in_collections = "saved_collections" in name
        n = 0
        if in_collections:
            # Every collection, in file order, including empty ones: a header table is one
            # whose own rows include Name and Type.
            memo, headers = {}, {}
            for t in root.elements("table"):
                memo[id(t)] = label_rows(t)
                if is_header(memo[id(t)]):
                    headers[id(t)] = header(memo[id(t)])
                    collections.append(headers[id(t)])
        for a in post_anchors(root):
            s = read_save(a)
            n += 1
            if s["code"] not in saves:
                if in_collections:  # in a collection but not in saved_posts: kept, and flagged
                    s["only_in_collection"] = True
                order.append(s["code"])
                saves[s["code"]] = s
            if in_collections:
                t, _ = collection_of(a.up("table"), memo)
                if t is not None and s["code"] not in headers[id(t)]["codes"]:
                    headers[id(t)]["codes"].append(s["code"])
        log("export_file", file=name, posts=n)
    for col in collections:
        for code in col["codes"]:
            if col["name"] not in saves[code]["collections"]:
                saves[code]["collections"].append(col["name"])
    return acct, [saves[c] for c in order], collections


# ---------------------------------------------------------------------------- JSON (older exports)

def records(data):
    if isinstance(data, list):
        return data
    if isinstance(data, dict):
        for v in data.values():
            if isinstance(v, list):
                return v
    return []


def fields(rec):
    out = []
    for label, d in (rec.get("string_map_data") or {}).items():
        if isinstance(d, dict):
            out.append((label, d.get("value"), d.get("href"), d.get("timestamp")))
    for d in rec.get("label_values") or []:
        if isinstance(d, dict):
            out.append((d.get("label"), d.get("value"), d.get("href"), d.get("timestamp")))
    if rec.get("href") or rec.get("value"):
        out.append((None, rec.get("value"), rec.get("href"), rec.get("timestamp")))
    return out


def when_ts(ts):
    if not isinstance(ts, (int, float)) or ts <= 0:
        return None
    return dt.datetime.fromtimestamp(ts, dt.timezone.utc).strftime("%Y-%m-%dT%H:%M")


def read_json(files):
    saves, order, collections = {}, [], []
    for name, text in sorted(files, key=lambda f: "saved_collections" in f[0]):
        recs = records(json.loads(text))
        in_collections = "saved_collections" in name
        current = None
        for rec in recs:
            if not isinstance(rec, dict):
                continue
            fs = fields(rec)
            link = next((h for _, _, h, _ in fs if h and POST.search(h)), None)
            if not link:
                cname = next((v for label, v, _, _ in fs if label == "Name" and v), None)
                if in_collections and cname:
                    current = {"name": cname, "type": None, "privacy": None, "updated": None, "codes": []}
                    collections.append(current)
                continue
            m = POST.search(link)
            stamp = rec.get("timestamp") or next((t for _, _, _, t in fs if t), None)
            author = rec.get("title") or next((v for label, v, h, _ in fs if h == link and v), None)
            code = m.group(2)
            if code not in saves:
                order.append(code)
                saves[code] = {"code": code, "url": "https://www.instagram.com/%s/%s/" % (m.group(1), code),
                               "kind": KIND[m.group(1)], "caption": None, "hashtags": [],
                               "owner": {"username": author, "name": None, "url": None} if author else None,
                               "saved_at": when_ts(stamp), "saved_at_text": None, "collections": []}
            elif saves[code]["saved_at"] is None:
                saves[code]["saved_at"] = when_ts(stamp)
            if in_collections and current is not None and code not in current["codes"]:
                current["codes"].append(code)
        log("export_file", file=name, records=len(recs))
    for col in collections:
        for code in col["codes"]:
            if col["name"] not in saves[code]["collections"]:
                saves[code]["collections"].append(col["name"])
    return None, [saves[c] for c in order], collections


# ---------------------------------------------------------------------------- output

def read_export(path):
    files = saved_files(path)
    html = [f for f in files if f[0].endswith(".html")]
    if html:
        acct, saves, cols = read_html(html)
        return files, "html", acct, saves, cols
    acct, saves, cols = read_json([f for f in files if f[0].endswith(".json")])
    return files, "json", acct, saves, cols


DICTIONARY = "/usr/share/dict/words"


def dictionary_words(path=DICTIONARY):
    """Lower-cased plain words, so a list entry like "Travel" or "coffee" can be left out."""
    try:
        with open(path, encoding="utf-8", errors="ignore") as fh:
            return {w.strip().lower() for w in fh if w.strip()}
    except OSError:
        return set()


def ordinary(item, words):
    """A plain dictionary word, or its plural ("tools" when the dictionary only has "tool")."""
    w = item.lower()
    return w in words or (w.endswith("s") and w[:-1] in words) or (w.endswith("es") and w[:-2] in words)


def never_public(acct, saves, collections, words=None):
    """The private strings, one per line: account, collection names, creators, post codes.

    A single ordinary word ("California", "recipes", or a plural like "tools") is left out: blocking it would stop normal
    writing in the plugin, and on its own it says nothing about the account. Phrases, handles
    with digits or underscores, and post codes stay in.
    """
    words = dictionary_words() if words is None else words
    items = set()
    if acct:
        items.add(acct)
    for c in collections:
        if len(c["name"]) >= 3:
            items.add(c["name"])
    for s in saves:
        items.add(s["code"])
        u = (s.get("owner") or {}).get("username")
        if u and len(u) >= 4:
            items.add(u)
    return sorted(i for i in items if " " in i.strip() or not ordinary(i, words))


def write_import(a):
    files, fmt, acct, saves, cols = read_export(a.export)
    if not files or not saves:
        log("import_empty", files=len(files),
            msg="no saved posts found: was Saved ticked in the export? see SKILL.md")
        return 1
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        json.dump({"exported": os.path.basename(a.export.rstrip("/")), "account": acct, "format": fmt,
                   "saves": saves, "collections": cols}, fh, indent=1, ensure_ascii=False)
    os.makedirs(os.path.dirname(a.never_public) or ".", exist_ok=True)
    with open(a.never_public, "w", encoding="utf-8") as fh:
        fh.write("\n".join(never_public(acct, saves, cols)) + "\n")
    kinds = {}
    for s in saves:
        kinds[s["kind"]] = kinds.get(s["kind"], 0) + 1
    listed = [s for s in saves if not s.get("only_in_collection")]
    log("import", out=a.out, format=fmt, saves=len(listed), only_in_collection=len(saves) - len(listed),
        collections=len(cols), collection_links=sum(len(c["codes"]) for c in cols),
        saves_in_a_collection=sum(1 for s in listed if s["collections"]),
        reels=kinds.get("reel", 0), posts=kinds.get("post", 0), tv=kinds.get("tv", 0),
        no_caption=sum(1 for s in saves if not (s["caption"] or "").strip()))
    print(summary(listed, saves, cols, a.out, a.never_public))
    return 0


def summary(listed, saves, cols, out, never_public_path):
    """The import in plain words, so a newcomer need not decode the log line (trial finding)."""
    extra = len(saves) - len(listed)
    text = f"Imported {len(listed)} saved posts"
    if extra:
        text += f", plus {extra} found only in a collection, so {len(saves)} in all"
    text += f", and {len(cols)} collections."
    names = {}
    for c in cols:
        names[c["name"]] = names.get(c["name"], 0) + 1
    for name, n in sorted(names.items()):
        if n > 1:
            times = "twice" if n == 2 else f"{n} times"
            text += f" '{name}' appears {times} because {n} collections share that name."
    return (text + f"\nWrote {out}.\n{never_public_path} lists your account, collection names, "
            "creators and post codes, so a check before each commit can stop them reaching anything "
            "public; you only need it if you share code (see SKILL.md).")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("export", nargs="?", help="the downloaded export .zip, or the folder it unzips to")
    ap.add_argument("--from-zip", dest="from_zip", help="the export .zip (read in memory, Saved files only)")
    ap.add_argument("--out", default=None)
    ap.add_argument("--saved", default=None, help="the file an earlier import wrote")
    ap.add_argument("--never-public", dest="never_public", default=None)
    ap.add_argument("--list", action="store_true", help="each collection and its post count")
    ap.add_argument("--collection", help="print this collection's post links")
    a = ap.parse_args(argv)
    a.export = a.from_zip or a.export
    a.out = a.out or cache("saves.json")
    a.saved = a.saved or a.out
    a.never_public = a.never_public or cache("never-public.txt")

    if a.export:
        return write_import(a)

    if not os.path.exists(a.saved):
        log("import_missing", saved=a.saved, msg="run with the export zip first")
        return 1
    with open(a.saved, encoding="utf-8") as fh:
        data = json.load(fh)
    by_code = {s["code"]: s for s in data["saves"]}
    if a.collection:
        cols = [c for c in data["collections"] if c["name"].lower() == a.collection.lower()]
        if not cols:
            log("collection_missing", name=a.collection)
            return 1
        seen = set()
        for c in cols:
            for code in c["codes"]:
                if code not in seen:
                    seen.add(code)
                    print(by_code[code]["url"])
        return 0
    if not a.collection:
        print(f"No export given, so this lists the collections from {a.saved}; "
              "pass the export zip to import again.", file=sys.stderr)
    print("%5d  %s" % (len(data["saves"]), "All saved"))
    for c in sorted(data["collections"], key=lambda c: (-len(c["codes"]), c["name"])):
        print("%5d  %s" % (len(c["codes"]), c["name"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
