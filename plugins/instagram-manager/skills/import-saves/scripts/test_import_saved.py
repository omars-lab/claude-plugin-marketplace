def write_zip(folder, files, private=True):
    path = os.path.join(folder, "instagram-export.zip")
    with zipfile.ZipFile(path, "w") as z:
        for name, text in files.items():
            z.writestr(name, text)
        if private:
            for name, text in PRIVATE.items():
                z.writestr(name, text)
    return path


def run(argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = import_saved.main(argv)
    return code, out.getvalue(), err.getvalue()


def html_zip(d):
    return write_zip(d, {"your_instagram_activity/saved/saved_posts.html": SAVED_POSTS,
                         "your_instagram_activity/saved/saved_collections.html": SAVED_COLLECTIONS})


class HtmlExport(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.d = self.tmp.name
        self.out = os.path.join(self.d, "saves.json")
        self.np = os.path.join(self.d, "never-public.txt")

    def tearDown(self):
        self.tmp.cleanup()

    def load(self):
        code, _, err = run(["--from-zip", html_zip(self.d), "--out", self.out, "--never-public", self.np])
        self.assertEqual(code, 0, err)
        with open(self.out, encoding="utf-8") as fh:
            data = json.load(fh)
        return data, {s["code"]: s for s in data["saves"]}, err

    def test_counts_match_the_export(self):
        data, saves, err = self.load()
        self.assertIn("saves=4 only_in_collection=1 collections=4 collection_links=5 saves_in_a_collection=3", err)
        self.assertEqual([s["code"] for s in data["saves"]],
                         ["FXa1Reel001", "FXb2Post002", "FXc3Tv00003", "FXd4Reel004", "FXe5Only005"])
        self.assertEqual(data["account"], "fixture.account")
        self.assertEqual(data["format"], "html")

    def test_caption_is_verbatim_with_entities_decoded(self):
        _, saves, _ = self.load()
        self.assertEqual(saves["FXa1Reel001"]["caption"],
                         "Two spots & a view\n\n📍 Fixture Cafe\n@fixture_cafe_02 is open late")
        self.assertEqual(saves["FXb2Post002"]["caption"], "")
        self.assertEqual(saves["FXc3Tv00003"]["caption"], "Line one\nLine two")

    def test_owner_hashtags_kind_and_time(self):
        _, saves, _ = self.load()
        cafe = saves["FXa1Reel001"]
        self.assertEqual(cafe["owner"], {"username": "fixture_eats_01", "name": "Fixture Eats | Food",
                                         "url": "https://example.com/eats"})
        self.assertEqual(cafe["hashtags"], ["fixturetown", "fixturefood"])
        self.assertEqual((cafe["kind"], cafe["url"]), ("reel", "https://www.instagram.com/reel/FXa1Reel001/"))
        self.assertEqual((cafe["saved_at"], cafe["saved_at_text"]), ("2026-01-05T21:07", "Jan 05, 2026 9:07 pm"))
        self.assertEqual(saves["FXb2Post002"]["owner"]["url"], None)
        self.assertEqual(saves["FXb2Post002"]["kind"], "post")
        self.assertEqual(saves["FXc3Tv00003"]["saved_at"], "2024-03-01T00:00")
        self.assertEqual(saves["FXe5Only005"]["saved_at"], None)  # collections carry no save time

    def test_collections_keep_duplicate_names_and_double_tags(self):
        data, saves, _ = self.load()
        self.assertEqual([(c["name"], c["codes"]) for c in data["collections"]],
                         [("Fixture Town", ["FXa1Reel001", "FXb2Post002"]), ("Fixture Town", ["FXc3Tv00003"]),
                          ("Fixture Recipes", ["FXa1Reel001", "FXe5Only005"]), ("Fixture Empty", [])])
        self.assertEqual(saves["FXa1Reel001"]["collections"], ["Fixture Town", "Fixture Recipes"])
        self.assertEqual(saves["FXd4Reel004"]["collections"], [])
        self.assertTrue(saves["FXe5Only005"]["only_in_collection"])
        self.assertEqual(data["collections"][0]["updated"], "2025-08-03T13:12")

    def test_only_the_saved_files_are_opened(self):
        opened = []
        real = zipfile.ZipFile.read

        def spy(self, name, *a, **k):
            opened.append(name if isinstance(name, str) else name.filename)
            return real(self, name, *a, **k)

        zipfile.ZipFile.read = spy
        try:
            self.load()
        finally:
            zipfile.ZipFile.read = real
        self.assertEqual(sorted(opened), ["your_instagram_activity/saved/saved_collections.html",
                                          "your_instagram_activity/saved/saved_posts.html"])

    def test_never_public_list(self):
        self.load()
        with open(self.np, encoding="utf-8") as fh:
            got = fh.read().split("\n")
        for want in ("fixture.account", "Fixture Town", "FXa1Reel001", "fixture_eats_01"):
            self.assertIn(want, got)

    def test_never_public_leaves_out_ordinary_words(self):
        saves = [{"code": "FXa1Reel001", "owner": {"username": "travel"}},
                 {"code": "FXb2Post002", "owner": {"username": "fixture_eats_01"}}]
        cols = [{"name": "Recipes"}, {"name": "Weekend Trips"}]
        got = import_saved.never_public("fixture.account", saves, cols, words={"travel", "recipes", "weekend"})
        self.assertEqual(got, ["FXa1Reel001", "FXb2Post002", "Weekend Trips", "fixture.account", "fixture_eats_01"])

    def test_list_and_collection(self):
        self.load()
        code, text, _ = run(["--collection", "fixture town", "--saved", self.out])
        self.assertEqual(code, 0)
        self.assertEqual(text.split(), ["https://www.instagram.com/reel/FXa1Reel001/",
                                        "https://www.instagram.com/p/FXb2Post002/",
                                        "https://www.instagram.com/tv/FXc3Tv00003/"])
        code, text, _ = run(["--list", "--saved", self.out])
        self.assertIn("2  Fixture Town", text)
        self.assertIn("5  All saved", text)
        code, _, err = run(["--collection", "Nowhere", "--saved", self.out])
        self.assertEqual(code, 1)
        self.assertIn("ev=collection_missing", err)

    def test_an_export_without_saved_is_an_error(self):
        code, _, err = run(["--from-zip", write_zip(self.d, {}), "--out", self.out, "--never-public", self.np])
        self.assertEqual(code, 1)
        self.assertIn("ev=import_empty", err)


