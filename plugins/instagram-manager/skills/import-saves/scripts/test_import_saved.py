class JsonExport(unittest.TestCase):
    def test_string_map_shape_from_a_zip(self):
        with tempfile.TemporaryDirectory() as d:
            z = write_zip(d, {"your_instagram_activity/saved/saved_posts.json": json.dumps(SAVED_POSTS_JSON),
                              "your_instagram_activity/saved/saved_collections.json": json.dumps(COLLECTIONS_JSON)})
            out = os.path.join(d, "saves.json")
            code, _, err = run([z, "--out", out, "--never-public", os.path.join(d, "np.txt")])
            self.assertEqual(code, 0, err)
            with open(out, encoding="utf-8") as fh:
                data = json.load(fh)
            saves = {s["code"]: s for s in data["saves"]}
            self.assertEqual(data["format"], "json")
            self.assertEqual(saves["JSa1Post001"]["collections"], ["Fixture Town"])
            self.assertEqual(saves["JSb2Reel002"]["url"], "https://www.instagram.com/reel/JSb2Reel002/")
            self.assertEqual(saves["JSa1Post001"]["owner"]["username"], "fixture_eats_01")
            self.assertEqual(saves["JSa1Post001"]["saved_at"], "2023-11-14T22:13")

    def test_labelled_shape_from_a_folder(self):
        with tempfile.TemporaryDirectory() as d:
            os.makedirs(os.path.join(d, "export", "saved"))
            with open(os.path.join(d, "export", "saved", "saved_collections.json"), "w") as fh:
                json.dump(LABELLED, fh)
            out = os.path.join(d, "saves.json")
            code, _, err = run([os.path.join(d, "export"), "--out", out, "--never-public", os.path.join(d, "np.txt")])
            self.assertEqual(code, 0, err)
            with open(out, encoding="utf-8") as fh:
                post = json.load(fh)["saves"][0]
            self.assertEqual(post["url"], "https://www.instagram.com/p/JSc3Post003/")
            self.assertEqual(post["collections"], ["Fixture Parks"])


