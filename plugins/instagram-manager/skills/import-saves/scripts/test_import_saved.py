BOX = '<div class="pam _3-95 _2ph- _a6-g uiBoxWhite noborder">'
INNER = '<div class="_a6-p">'
H2 = '<h2 class="_3-95 _2pim _a6-h _a6-i">%s</h2>'


def owner(username, name, url=None):
    rows = ""
    if url:
        rows += '<tr><td class="_a6_q">URL</td><td class="_2piu _a6_r">%s</td></tr>' % url
    rows += '<tr><td class="_a6_q">Name</td><td class="_2piu _a6_r">%s</td></tr>' % name
    rows += '<tr><td class="_a6_q">Username</td><td class="_2piu _a6_r">%s</td></tr>' % username
    return ('<tr><td colspan="2" class="_a6_q"><div>' + BOX + H2 % "Owner" + INNER + BOX + INNER
            + '<table style="table-layout: fixed;"><tr><td colspan="2" class="_a6_q"><div>' + BOX + INNER
            + BOX + INNER + '<table style="table-layout: fixed;">' + rows + '</table>'
            + '</div></div></div></div></td></tr></table></div></div></div></div></td></tr>')


def hashtags(tags):
    if not tags:
        return ""
    items = "".join('<div>' + BOX + '<div class="_a6-p">%s</div></div></div>' % t for t in tags)
    return ('<tr><td colspan="2" class="_a6_q"><div>' + BOX + H2 % "Hashtags" + '<div class="_a6-p"><div>'
            + '<div class="_2ph_ _a6_q">Name</div><div>' + items + '</div></div></div></div></div></td></tr>')


def save_table(kind, code, caption, tags, who):
    url = "https://www.instagram.com/%s/%s/" % (kind, code)
    return ('<table style="table-layout: fixed;"><tr><td colspan="2" class="_a6_q">URL<div>'
            '<a target="_blank" href="%s">%s</a></div></td></tr>' % (url, url)
            + '<tr><td class="_a6_q">Caption</td><td class="_2piu _a6_r">%s</td></tr>' % caption
            + hashtags(tags) + owner(*who) + '</table>')


def page(title, body):
    return ('<html><head><meta http-equiv="Content-Type" content="text/html; charset=UTF-8" />'
            '<style type="text/css">td{color:#000}</style><title>%s</title></head><body>'
            '<header><aside role="contentinfo" class="_aoaa">Generated by fixture.account on '
            '<time datetime="2026-01-01T00:00Z">Thursday, January 1, 2026</time></aside></header>'
            '<main class="_a706" role="main">%s</main></body></html>' % (title, body))


def posts_page(saves):
    body = ""
    for kind, code, caption, tags, who, when in saves:
        body += (BOX + '<div class="_3-95 _a6-p">' + BOX + INNER + save_table(kind, code, caption, tags, who)
                 + '</div></div></div><div class="_3-94 _a6-o">%s</div></div>' % when)
    return page("Saved posts", body)


def collections_page(cols):
    body = ""
    for name, saves in cols:
        media = "".join('<tr><td colspan="2" class="_a6_q"><div>' + BOX + INNER + BOX + INNER
                        + save_table(*s) + '</div></div></div></div></td></tr>' for s in saves)
        body += (BOX + '<div class="_3-95 _a6-p">' + BOX + INNER + '<table style="table-layout: fixed;">'
                 '<tr><td class="_a6_q">Name</td><td class="_2piu _a6_r">%s</td></tr>' % name
                 + '<tr><td class="_a6_q">Type</td><td class="_2piu _a6_r">Default</td></tr>'
                 '<tr><td class="_a6_q">Privacy</td><td class="_2piu _a6_r">Private</td></tr>'
                 '<tr><td class="_a6_q">Update time</td><td class="_2piu _a6_r">Aug 03, 2025 1:12 pm</td></tr>'
                 + ('<tr><td colspan="2" class="_a6_q"><div>' + BOX + H2 % "Media" + INNER + BOX + INNER
                    + '<table style="table-layout: fixed;">' + media + '</table></div></div></div></div></td></tr>'
                    if saves else "")
                 + '</table></div></div></div></div>')
    return page("Saved collections", body)


