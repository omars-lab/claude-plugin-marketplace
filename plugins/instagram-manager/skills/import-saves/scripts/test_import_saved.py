"""Offline checks for import_saved.py, on small invented exports in the shapes Instagram has used.

    python3 skills/import-saves/scripts/test_import_saved.py

Every handle, code and collection name here is made up (this plugin is public). The HTML
templates copy the real export's nesting: a save is a table whose first cell is "URL" plus the
post link, then a Caption row, then Hashtags and Owner sections in colspan cells; saved_posts
adds a save-time div after the table; saved_collections wraps posts in a collection header
table (Name / Type / Privacy / Update time) with a Media section.
"""

